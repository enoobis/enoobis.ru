function parseSvg(svg) {
  const viewBoxMatch = svg.match(/viewBox="([^"]+)"/);
  if (!viewBoxMatch) throw new Error("missing viewBox");
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error("no paths");
  return { viewBox: viewBoxMatch[1], paths };
}

/** @type {Record<string, { viewBox: string; paths: string[] }>} */
const data = {};

for (const [name, rel] of Object.entries(mapping)) {
  const file = path.join(srcRoot, rel);
  if (!fs.existsSync(file)) {
    console.error(`missing: ${rel} (${name})`);
    process.exitCode = 1;
    continue;
  }
  data[name] = parseSvg(fs.readFileSync(file, "utf8"));
}

const iconNames = Object.keys(mapping);
const lines = [
  "// generated by scripts/generate-doodle-icons.mjs — Khushmeen Doodle Icons (CC0)",
  "export type DoodleIconName =",
  ...iconNames.map((n, i) => `  | "${n}"${i === iconNames.length - 1 ? ";" : ""}`),
  "",
  "export type DoodleIconDef = { viewBox: string; paths: string[] };",
  "",
  "export const doodleIconData: Record<DoodleIconName, DoodleIconDef> = {",
];

for (const name of iconNames) {
  const def = data[name];
  if (!def) continue;
  lines.push(`  ${name}: {`);
  lines.push(`    viewBox: "${def.viewBox}",`);
  lines.push(`    paths: [`);
  for (const p of def.paths) {
    lines.push(`      ${JSON.stringify(p)},`);
  }
  lines.push(`    ],`);
  lines.push(`  },`);
}

lines.push("};", "");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile} (${iconNames.length} icons)`);
